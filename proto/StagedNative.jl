"""Small source-generating experiment, deliberately independent of the runtime image."""
module StagedNative

export BakedPool, ExportSpec, ProgramSpec, generate, build

struct BakedPool
    n::Int
    function BakedPool(n::Integer)
        0 < n <= typemax(UInt32) || throw(ArgumentError("pool size must fit a nonzero UInt32"))
        new(n)
    end
end

const HOST_TYPES = (Int8, UInt8, Int16, UInt16, Int32, UInt32, Int64, UInt64, Float32, Float64)
const C_TYPES = ("int8_t", "uint8_t", "int16_t", "uint16_t", "int32_t", "uint32_t",
                 "int64_t", "uint64_t", "float", "double")
identifier(x) = occursin(r"^[A-Za-z_][A-Za-z_0-9]*$", string(x))
function hosttype(t)
    t in HOST_TYPES || throw(ArgumentError("unsupported fixed-width host type: $t"))
    t
end
ctype(t) = C_TYPES[findfirst(==(hosttype(t)), HOST_TYPES)]

struct ExportSpec
    name::Symbol
    f::Function
    argtypes::Tuple
    returns::Type
    function ExportSpec(name, f, argtypes; returns=Nothing)
        identifier(name) || throw(ArgumentError("invalid export name"))
        Symbol(name) in (:create, :destroy) && throw(ArgumentError("reserved lifecycle export"))
        foreach(hosttype, argtypes)
        returns === Nothing || hosttype(returns)
        new(Symbol(name), f, Tuple(argtypes), returns)
    end
end

struct ProgramSpec
    name::Symbol
    setup::Function
    config
    exports::Vector{ExportSpec}
    instances::BakedPool
    reset::Function
end
function ProgramSpec(; name, setup, config, exports, instances=BakedPool(1), reset)
    identifier(name) || throw(ArgumentError("invalid program name"))
    length(unique(e.name for e in exports)) == length(exports) || throw(ArgumentError("duplicate exports"))
    ProgramSpec(Symbol(name), setup, config, collect(exports), instances, reset)
end

# This prototype transports references to named functions, not closures or arbitrary
# heap graphs. The supplied source must define the same modules in the image process.
function functionref(f)
    m, n = parentmodule(f), nameof(f)
    identifier(n) && isdefined(m, n) && getglobal(m, n) === f ||
        throw(ArgumentError("use a named, module-level function"))
    parts = filter(!=(:Main), collect(Base.fullname(m)))
    join(string.([parts; n]), ".")
end
function literal(x)
    x === nothing && return "nothing"
    x isa Union{Bool, AbstractString, Symbol} && return repr(x)
    if typeof(x) in HOST_TYPES
        return "$(typeof(x))($(repr(x)))"
    elseif x isa NamedTuple
        return "(; " * join(["$k = $(literal(v))" for (k, v) in pairs(x)], ", ") * ")"
    elseif x isa Tuple
        return "(" * join(literal.(x), ", ") * (length(x) == 1 ? ",)" : ")")
    end
    throw(ArgumentError("config supports scalar host types, strings, symbols, tuples and named tuples"))
end

"""
    generate(spec; source, output_dir)

Write build.jl and program.h. `source` defines the named setup/reset/export
functions. Setup runs only when JuliaC includes build.jl in its image process.
Symbols are prefixed by the program name. The ABI is single-threaded and uses
UInt64 handles (high 32 bits generation, low 32 bits one-based slot).
"""
function generate(spec::ProgramSpec; source, output_dir)
    source = abspath(source)
    isfile(source) || throw(ArgumentError("missing program source: $source"))
    dir = abspath(output_dir)
    mkpath(dir)
    prefix = string(spec.name)
    setup, reset = functionref(spec.setup), functionref(spec.reset)
    n = spec.instances.n
    src = IOBuffer()
    println(src, "# Generated by StagedNative. Setup executes in the image-building process.")
    println(src, "include(", repr(source), ")")
    println(src, "module Staged_", prefix)
    # Qualified Main references resolve definitions from the included source.
    println(src, "const STATES = let config = ", literal(spec.config))
    println(src, "    first = Main.$setup(config)")
    println(src, "    states = Vector{typeof(first)}(undef, $n)")
    println(src, "    states[1] = first")
    println(src, "    for i in 2:$n; states[i] = Main.$setup(config); end")
    println(src, "    states\nend")
    println(src, "const ACTIVE = fill(false, $n)")
    println(src, "const GENERATION = fill(UInt32(1), $n)")
    println(src, raw"""
@inline function lookup(h::UInt64)::Int
    slot = UInt32(h & UInt64(0xffffffff))
    gen = UInt32(h >> 32)
    if slot == 0 || slot > length(STATES) || gen == 0
        return 0
    end
    i = Int(slot)
    @inbounds return ACTIVE[i] && GENERATION[i] == gen ? i : 0
end
""")
    println(src, "Base.@ccallable function $(prefix)_create(out::Ptr{UInt64})::Int32")
    println(src, "    out == C_NULL && return Int32(3)")
    println(src, "    for i in eachindex(STATES)")
    println(src, "        if !ACTIVE[i] && GENERATION[i] != 0")
    println(src, "            try; Main.$reset(STATES[i]); catch; return Int32(4); end")
    println(src, "            ACTIVE[i] = true")
    println(src, "            unsafe_store!(out, (UInt64(GENERATION[i]) << 32) | UInt64(i))")
    println(src, "            return Int32(0)\n        end\n    end\n    return Int32(2)\nend")
    println(src, "Base.@ccallable function $(prefix)_destroy(h::UInt64)::Int32")
    println(src, "    i = lookup(h); i == 0 && return Int32(1)")
    println(src, "    ACTIVE[i] = false")
    # Wrapping to zero permanently retires a slot: never alias an ancient handle.
    println(src, "    GENERATION[i] += UInt32(1)\n    return Int32(0)\nend")
    for e in spec.exports
        args = String["a$i::$(t)" for (i, t) in enumerate(e.argtypes)]
        e.returns === Nothing || push!(args, "out::Ptr{$(e.returns)}")
        println(src, "Base.@ccallable function $(prefix)_$(e.name)(h::UInt64",
                isempty(args) ? "" : ", " * join(args, ", "), ")::Int32")
        e.returns === Nothing || println(src, "    out == C_NULL && return Int32(3)")
        println(src, "    i = lookup(h); i == 0 && return Int32(1)")
        call = "Main.$(functionref(e.f))(STATES[i]" *
               join([", a$i" for i in eachindex(e.argtypes)]) * ")"
        println(src, "    try")
        if e.returns === Nothing
            println(src, "        $call")
        else
            println(src, "        result = $call::$(e.returns)")
            println(src, "        unsafe_store!(out, result)")
        end
        println(src, "        return Int32(0)\n    catch\n        return Int32(4)\n    end\nend")
    end
    println(src, "end # generated module")
    # Force collection so the local-garbage comparison does not depend on GC timing.
    println(src, "GC.gc(true)")
    build_source = joinpath(dir, "build.jl")
    write(build_source, String(take!(src)))
    header = joinpath(dir, "program.h")
    open(header, "w") do io
        guard = uppercase(prefix) * "_PROGRAM_H"
        println(io, "#ifndef $guard\n#define $guard\n#include <stdint.h>")
        println(io, "#ifdef __cplusplus\nextern \"C\" {\n#endif")
        println(io, "/* Single host thread; Julia ccallable entrypoints auto-initialize the runtime.")
        println(io, " * The caller supplies valid writable out pointers (null is checked).")
        println(io, " * Outputs remain unchanged on failure; exceptions may mutate state.")
        println(io, " * Handle: generation << 32 | slot; 0 is invalid. No generation reuse. */")
        println(io, "enum { $(prefix)_OK=0, $(prefix)_INVALID=1, $(prefix)_EXHAUSTED=2,")
        println(io, "       $(prefix)_NULL=3, $(prefix)_EXCEPTION=4 };")
        println(io, "int32_t $(prefix)_create(uint64_t *out);")
        println(io, "int32_t $(prefix)_destroy(uint64_t h);")
        for e in spec.exports
            args = ["uint64_t h"; ["$(ctype(t)) a$i" for (i, t) in enumerate(e.argtypes)]]
            e.returns === Nothing || push!(args, "$(ctype(e.returns)) *out")
            println(io, "int32_t $(prefix)_$(e.name)(", join(args, ", "), ");")
        end
        println(io, "#ifdef __cplusplus\n}\n#endif\n#endif")
    end
    (; build_source, header, dir)
end

"""Generate and drive JuliaC's compile → link → optional bundle recipes."""
function build(spec::ProgramSpec; source, output_dir, project, trim_mode="safe", bundle=false)
    files = generate(spec; source, output_dir)
    # Keep JuliaC and all its dependencies out of generated build.jl.
    @eval import JuliaC
    Base.invokelatest() do
        img = JuliaC.ImageRecipe(file=files.build_source, output_type="--output-lib",
            project=abspath(project), trim_mode=trim_mode, add_ccallables=true,
            cpu_target="native", export_abi=joinpath(files.dir, "abi.json"),
            img_path=joinpath(files.dir, "image.o.a"))
        JuliaC.compile_products(img)
        link = JuliaC.LinkRecipe(image_recipe=img, outname=joinpath(files.dir, "lib$(spec.name)"))
        JuliaC.link_products(link)
        if bundle
            JuliaC.bundle_products(JuliaC.BundleRecipe(link_recipe=link,
                output_dir=joinpath(files.dir, "bundle")))
        end
        (; files..., library=link.outname)
    end
end
end
